/*
 * SPDX-License-Identifier: BSD-3-Clause
 *
 * apu_gas.h —— 气体传感器（直接挂 UART-A 的 PL 串口）
 * ===========================================================================
 *  【与下潜深度超声的分工】
 *      UART-A : 气体传感器   <-- 本模块
 *      UART-C : 下潜深度超声 <-- apu_depth.c
 *  两者都是"一问一答"的 TTL 串口设备，物理独立。
 *
 *  【协议来源】
 *      《气体传感器模组规格书 v1.10》第 6~10 页
 *      硬件：把传感器的 +、-、R、T 接到 5V/GND/TXD/RXD（**用户端 TTL 电平**）
 *            ⚠️ 传感器 TXD -> FPGA RX(UART-A 的 V10)
 *               传感器 RXD <- FPGA TX(UART-A 的 V11)
 *               交叉接；A 路没有 DE 方向脚，是纯 3 线 TTL
 *
 *  ── 软件设置（规格书原文）──────────────────────────────────────────────
 *      UART 接口采用标准的 MODBUS-RTU 通讯协议。
 *      波特率 9600，数据位 8，停止位 1，奇偶校验 无。   ← 注意是 9600，不是 115200！
 *
 *  ── 主机查询帧（功能码 0x03 读保持寄存器）────────────────────────────
 *      01 03 00 00 00 0A C5 CD
 *      |  |  |     |     |  └── CRC16(低字节在前)
 *      |  |  |     |     └───── 读 10 个寄存器
 *      |  |  |     └─────────── 起始寄存器 0x0000
 *      |  |  └───────────────── 功能码 03
 *      |  └──────────────────── 从机地址（可配，默认 0x01）
 *      └─────────────────────── 起始字节
 *
 *  ── 从机应答帧（固定 25 字节）─────────────────────────────────────────
 *      [0]      从机地址
 *      [1]      功能码 0x03
 *      [2]      字节数 = 0x14 = 20
 *      [3..22]  10 个寄存器，**每寄存器 2 字节，高字节在前**（大端）
 *      [23][24] CRC16，低字节在前
 *
 *  ── 10 个寄存器映射 ───────────────────────────────────────────────────
 *      [0] 单位 / 小数点 / 各值的高位（编码见下）
 *      [1] 当前气体浓度
 *      [2] 低报设定值
 *      [3] 高报设定值
 *      [4] 全量程值
 *      [5] 传感器工作状态（低 8 位）
 *      [6] 传感器实时 AD 值
 *      [7] 环境温度值
 *      [8] 气体类型（高 8 位有效）
 *      [9] 环境湿度
 *
 *  ── 寄存器 [0] 的位定义 ───────────────────────────────────────────────
 *      bit15-12 数值单位:  0000=ppm  0010=%LEL  0100=%VOL  0110=mg/m3  1000=ppb
 *      bit11-8  小数点位数: 0000=无小数  0100=一位  1000=两位  1100=三位
 *      bit6-7   当前浓度的最高位(第17、18位)
 *      bit4-5   低报限的最高位
 *      bit2-3   高报限的最高位
 *      bit0-1   满量程值的最高位
 *      （数据区只有 16 位，最大 65535；需要更大时把最高位补进来 → 最大 262143）
 *
 *  ── 工作状态字 ────────────────────────────────────────────────────────
 *      0x00 预热      0x01 正常      0x02 数据错误   0x03 传感器故障
 *      0x04 预警      0x05 低报      0x06 高报       0x07 访问故障
 *      0x08 超量程    0x09 需要标定  0x0A 超时       0x0B stel报警
 *      0x0C twa报警   0x0F 通信故障
 *
 *  ⚠️ 【重要】规格书第 7 页那帧"从机响应"示例的 CRC 是**错的**。
 *     已用官方 Modbus 测试向量验证过本模块的 CRC16 实现：
 *         请求 01 03 00 00 00 0A -> CRC C5 CD  （与规格书一致 ✓）
 *         而那帧响应示例用前 23 字节算出的是 DE 75，规格书写的是 B6 87，
 *         穷举所有起始/长度/字节序都凑不出来 —— 是文档笔误。
 *     ⇒ **示例帧不可信，寄存器映射与帧结构可信**，真值以上板实测为准。
 *
 *  【怎么让路】
 *      本模块只为"打通链路 + 打串口1验证"而加（与 apu_depth.c 同策略）。
 *      刻意不依赖任何业务模块，删起来是干净的。
 * ===========================================================================
 */

